// Pack the example programs in samples/ into src/ide/samples-data.js.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'samples');
const files = {};
const walk = (d) => {
  for (const n of readdirSync(d).sort()) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else files[relative(dir, p).split('\\').join('/')] = readFileSync(p, 'utf8');
  }
};
walk(dir);
const out = '// Generated by tools/gen-samples.mjs from samples/. Do not edit.\n(function (LG) {\n  LG.SAMPLE_FILES = ' + JSON.stringify(files, null, 0) + ';\n})(LG);\n';
writeFileSync(join(root, 'src/ide/samples-data.js'), out);
console.log('samples-data.js: ' + Object.keys(files).length + ' examples');
