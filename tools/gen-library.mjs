// Packs library/<CATEGORY>/*.lgo into src/ide/library-data.js:
//   LG.LIBRARY = { categories: [...], items: [{path, cat, title, level, tags, summary}], blob: '<base64 deflate-raw JSON>' }
// The program texts live in the compressed blob and are unpacked only when the library is opened.
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateRawSync } from 'node:zlib';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lib = join(root, 'library');
export const CATEGORIES = {
  shapes: ['Shapes & Polygons', 'Squares, stars and every regular shape, the turtle way.'],
  patterns: ['Patterns & Mandalas', 'Repeat a shape, turn a little, and something beautiful appears.'],
  spirals: ['Spirals & Curves', 'Growing steps, shrinking turns and the curves they make.'],
  fractals: ['Fractals', 'Shapes made of smaller copies of themselves.'],
  art: ['Generative Art & Colour', 'Randomness, colour mixing and pictures that draw themselves.'],
  animation: ['Animation & Many Turtles', 'Moving pictures, bouncing balls and turtles working together.'],
  games: ['Games', 'Things to play: keyboard, mouse and guessing games.'],
  puzzles: ['Puzzles & Logic', 'Classic puzzles solved by the computer, and some for you.'],
  math: ['Mathematics', 'Numbers, sequences, graphs and calculations.'],
  geometry: ['Geometry & Trigonometry', 'Angles, circles, triangles and the maths of the turtle.'],
  numbers: ['Number Theory', 'Primes, divisors, digits and patterns in whole numbers.'],
  words: ['Words & Text', 'Playing with words and sentences: Logo was made for this.'],
  data: ['Lists & Data Structures', 'Lists, arrays, property lists, stacks, queues and trees.'],
  algorithms: ['Algorithms', 'Sorting, searching and other recipes every programmer knows.'],
  recursion: ['Recursion', 'Procedures that use themselves, made to be watched in the debugger.'],
  science: ['Science & Simulation', 'Physics, biology and chance, simulated step by step.'],
  music: ['Music & Sound', 'Tones, tunes and rhythms on the speaker.'],
  files: ['Files & Data', 'Programs that write, read and keep information.'],
  school: ['School Helpers & Quizzes', 'Practice times tables, spelling, fractions and more.'],
  stories: ['Stories, Chatbots & Language', 'Mad libs, poems, conversations and word games.'],
  classic: ['Classic Logo', 'Programs in the style of the early Logo books and computers.'],
};
const items = [], texts = {};
const cats = existsSync(lib) ? readdirSync(lib).filter((d) => statSync(join(lib, d)).isDirectory()).sort((a, b) => Object.keys(CATEGORIES).indexOf(a) - Object.keys(CATEGORIES).indexOf(b)) : [];
for (const c of cats) {
  for (const f of readdirSync(join(lib, c)).filter((x) => /\.lgo$/i.test(x)).sort()) {
    const text = readFileSync(join(lib, c, f), 'utf8').replace(/\r\n?/g, '\n');
    const field = (k) => { const m = new RegExp('^;+\\s*' + k + ':\\s*(.*)$', 'mi').exec(text); return m ? m[1].trim() : ''; };
    const path = c + '/' + f;
    texts[path] = text;
    if (f.startsWith('_')) continue;
    const lv = (field('LEVEL').split(/\s/)[0] || 'Intermediate');
    items.push({ path, cat: c, title: field('TITLE') || f, level: lv[0].toUpperCase() + lv.slice(1).toLowerCase(), tags: field('TAGS').split(/\s*,\s*/).filter(Boolean), summary: field('SUMMARY') });
  }
}
const blob = deflateRawSync(Buffer.from(JSON.stringify(texts)), { level: 9 }).toString('base64');
const categories = cats.map((c) => ({ id: c, name: (CATEGORIES[c] || [c])[0], blurb: (CATEGORIES[c] || [])[1] || '', count: items.filter((i) => i.cat === c).length }));
writeFileSync(join(root, 'src/ide/library-data.js'), '// Generated by tools/gen-library.mjs from library/. Do not edit.\n(function (LG) {\n  LG.LIBRARY = ' +
  JSON.stringify({ categories, items }) + ';\n  LG.LIBRARY.blob = "' + blob + '";\n})(LG);\n');
if (import.meta.url === 'file://' + process.argv[1]) console.log(`library-data.js: ${items.length} programs in ${cats.length} categories, blob ${(blob.length / 1024).toFixed(0)} KB`);
